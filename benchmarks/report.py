"""Summarize raw measurements; no third-party Python dependencies."""

import datetime
import hashlib
import json
import pathlib
import platform
import re
import statistics
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent
SOURCE = pathlib.Path(subprocess.check_output(["go", "list", "-m", "-f", "{{.Dir}}", "github.com/hainuoli/mino"], cwd=ROOT, text=True).strip())


def command(*args):
    return subprocess.check_output(args, cwd=ROOT, text=True).strip()


def environment():
    sources = sorted(
        path
        for directory in (SOURCE / "core", SOURCE / "rest")
        for path in directory.rglob("*.go")
        if not path.name.endswith("_test.go")
    )
    digest = hashlib.sha256()
    for path in sources:
        digest.update(path.relative_to(SOURCE).as_posix().encode() + b"\0")
        digest.update(path.read_bytes() + b"\0")
    cpu = platform.processor()
    if sys.platform == "darwin":
        cpu = command("sysctl", "-n", "machdep.cpu.brand_string")
    elif pathlib.Path("/proc/cpuinfo").exists():
        cpu = next(
            (line.split(":", 1)[1].strip()
             for line in pathlib.Path("/proc/cpuinfo").read_text().splitlines()
             if line.startswith("model name")), cpu
        )
    return {
        "measured_at_utc": datetime.datetime.now(datetime.timezone.utc).isoformat(),
        "go": command("go", "version"),
        "platform": platform.platform(),
        "cpu": cpu,
        "base_commit": subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=SOURCE, text=True).strip(),
        "production_source_sha256": digest.hexdigest(),
        "production_source_modified_from_base": bool(subprocess.check_output(["git", "diff", "HEAD", "--", "core", "rest"], cwd=SOURCE, text=True).strip()),
        "benchmark_command": "go test -run '^$' -bench '^BenchmarkRouter$' -benchmem -benchtime=1s -count=5 -cpu=1",
        "go_environment": json.loads(command("go", "env", "-json", "GOOS", "GOARCH", "CGO_ENABLED", "GOFLAGS", "GOEXPERIMENT", "GOTOOLCHAIN")),
        "versions": {
            name: command("go", "list", "-m", "-f", "{{.Version}}", name)
            for name in ("github.com/gin-gonic/gin", "github.com/go-chi/chi/v5", "github.com/zeromicro/go-zero")
        },
    }


def summary():
    samples = {}
    pattern = re.compile(
        r"^BenchmarkRouter/(\w+)/(\w+)(?:-\d+)?\s+\d+\s+([\d.]+) ns/op\s+(\d+) B/op\s+(\d+) allocs/op$"
    )
    for line in (ROOT / "results/router.txt").read_text().splitlines():
        match = pattern.match(line)
        if match:
            scenario, framework, ns, size, allocations = match.groups()
            samples.setdefault((scenario, framework), []).append((float(ns), int(size), int(allocations)))
    if len(samples) != 24 or any(len(values) != 5 for values in samples.values()):
        raise ValueError("Expected all 24 benchmark cases with five samples each")
    print("<!-- Generated by python3 report.py; timing values are medians of five runs. -->\n")
    print("| Scenario | Mino ns/op | Gin ns/op | Chi ns/op | go-zero router ns/op |")
    print("| --- | ---: | ---: | ---: | ---: |")
    scenarios = list(dict.fromkeys(key[0] for key in samples))
    frameworks = ("Mino", "Gin", "Chi", "GoZero")
    for scenario in scenarios:
        values = [statistics.median(row[0] for row in samples[scenario, fw]) for fw in frameworks]
        print(f"| {scenario} | " + " | ".join(f"{value:.1f}" for value in values) + " |")
    print("\n| Scenario / framework | Median ns/op | Min–max ns/op | Median B/op | Median allocs/op |")
    print("| --- | ---: | ---: | ---: | ---: |")
    for (scenario, framework), rows in samples.items():
        ns, size, allocations = (statistics.median(row[i] for row in rows) for i in range(3))
        times = [row[0] for row in rows]
        print(f"| {scenario} / {framework} | {ns:.1f} | {min(times):.1f}–{max(times):.1f} | {size:.0f} | {allocations:.0f} |")
    footprint = json.loads((ROOT / "results/footprint.json").read_text())
    print("\n| Production package | Go files | Code lines | Source bytes |")
    print("| --- | ---: | ---: | ---: |")
    for package, size in sorted(footprint["source"].items()):
        print(f"| `{package}` | {size['files']} | {size['code_lines']} | {size['bytes']} |")
    print("\n| Minimal server | Binary bytes | MiB | Non-stdlib packages | Non-stdlib modules |")
    print("| --- | ---: | ---: | ---: | ---: |")
    for binary in footprint["binaries"]:
        print(f"| {binary['name']} | {binary['bytes']} | {binary['bytes'] / 2**20:.2f} | {binary['non_std_packages']} | {binary['non_std_modules']} |")


if __name__ == "__main__":
    if sys.argv[1:] == ["environment"]:
        print(json.dumps(environment(), indent=2))
    elif sys.argv[1:]:
        raise SystemExit("Usage: python3 report.py [environment]")
    else:
        summary()
